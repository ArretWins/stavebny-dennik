import { createHash } from "node:crypto";
import { mkdir, readFile, rename, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { createClient } from "@supabase/supabase-js";

type BackupFile = {
  path: string;
  bytes: number;
  sha256: string;
  storagePath?: string;
};
type BackupBucket = {
  id: string;
  public: boolean;
  fileSizeLimit: number | null;
  allowedMimeTypes: string[] | null;
  files: BackupFile[];
};

const dryRun = process.env.BACKUP_DRY_RUN === "1";
const useLinkedDatabase = process.env.BACKUP_USE_LINKED === "1";
const root = resolve(process.env.BACKUP_ROOT || "backups");
const stamp = new Date().toISOString().replace(/[:.]/g, "-");
const partial = join(root, `${stamp}.partial`);
const destination = join(root, stamp);
const dbUrl = process.env.SUPABASE_DB_URL || "";
const supabaseUrl =
  process.env.SUPABASE_URL || process.env.EXPO_PUBLIC_SUPABASE_URL || "";
const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY || "";

function required(value: string, name: string) {
  if (!value && !dryRun) throw new Error(`${name} is required`);
}
function diskSegment(value: string): string {
  if (!value) throw new Error("Empty storage path segment");
  if (value === ".") return "%2E";
  if (value === "..") return "%2E%2E";
  return encodeURIComponent(value).replace(/\*/g, "%2A");
}
async function fileInfo(
  path: string,
  relativePath: string,
): Promise<BackupFile> {
  const bytes = await readFile(path);
  return {
    path: relativePath.replaceAll("\\", "/"),
    bytes: bytes.byteLength,
    sha256: createHash("sha256").update(bytes).digest("hex"),
  };
}
function runSupabase(args: string[]) {
  const configured = process.env.SUPABASE_CLI;
  const command =
    configured || (process.platform === "win32" ? "npx.cmd" : "npx");
  const prefix = configured ? [] : ["supabase"];
  const result = spawnSync(command, [...prefix, ...args], {
    stdio: "inherit",
    // Node 24 cannot execute Windows .cmd shims directly with shell=false
    // (spawnSync returns EINVAL). All arguments here are generated by this
    // script, so invoking the trusted npm shim through cmd.exe is safe.
    shell: process.platform === "win32" && command.endsWith(".cmd"),
  });
  if (result.error) throw result.error;
  if (result.status !== 0)
    throw new Error(`Supabase CLI failed with status ${result.status}`);
}
async function dumpDatabase(): Promise<BackupFile[]> {
  const targets = [
    { name: "roles.sql", args: ["--role-only"] },
    { name: "schema.sql", args: [] },
    { name: "data.sql", args: ["--data-only", "--use-copy"] },
  ];
  const files: BackupFile[] = [];
  for (const target of targets) {
    const path = join(partial, "database", target.name);
    if (dryRun)
      await writeFile(path, `-- Stavba pilot dry-run ${target.name}\n`, "utf8");
    else
      runSupabase([
        "db",
        "dump",
        ...(useLinkedDatabase ? ["--linked"] : ["--db-url", dbUrl]),
        "--file",
        path,
        ...target.args,
      ]);
    files.push(await fileInfo(path, `database/${target.name}`));
  }
  return files;
}
async function backupStorage(): Promise<BackupBucket[]> {
  if (dryRun) return [];
  const client = createClient(supabaseUrl, serviceKey, {
    auth: { persistSession: false, autoRefreshToken: false },
  });
  const bucketsResult = await client.storage.listBuckets();
  if (bucketsResult.error) throw bucketsResult.error;
  const buckets: BackupBucket[] = [];
  for (const bucket of bucketsResult.data || []) {
    const bucketId = diskSegment(bucket.id);
    const files: BackupFile[] = [];
    const walk = async (prefix = "") => {
      for (let offset = 0; ; offset += 1000) {
        const listed = await client.storage.from(bucket.id).list(prefix, {
          limit: 1000,
          offset,
          sortBy: { column: "name", order: "asc" },
        });
        if (listed.error) throw listed.error;
        const entries = listed.data || [];
        for (const entry of entries) {
          const name = entry.name;
          if (!name)
            throw new Error(`Empty object name in bucket ${bucket.id}`);
          const storagePath = prefix ? `${prefix}/${name}` : name;
          if (entry.id === null || entry.metadata === null) {
            await walk(storagePath);
            continue;
          }
          const downloaded = await client.storage
            .from(bucket.id)
            .download(storagePath);
          if (downloaded.error || !downloaded.data)
            throw (
              downloaded.error ||
              new Error(`Unable to download ${bucket.id}/${storagePath}`)
            );
          const bytes = new Uint8Array(await downloaded.data.arrayBuffer());
          const localPath = join(
            partial,
            "storage",
            bucketId,
            ...storagePath.split("/").map(diskSegment),
          );
          await mkdir(resolve(localPath, ".."), { recursive: true });
          await writeFile(localPath, bytes);
          files.push({
            ...(await fileInfo(
              localPath,
              `storage/${bucketId}/${storagePath
                .split("/")
                .map(diskSegment)
                .join("/")}`,
            )),
            storagePath,
          });
        }
        if (entries.length < 1000) break;
      }
    };
    await walk();
    buckets.push({
      id: bucket.id,
      public: bucket.public,
      fileSizeLimit: bucket.file_size_limit ?? null,
      allowedMimeTypes: bucket.allowed_mime_types ?? null,
      files,
    });
  }
  return buckets;
}

async function main() {
  if (!useLinkedDatabase) required(dbUrl, "SUPABASE_DB_URL");
  required(supabaseUrl, "SUPABASE_URL");
  required(serviceKey, "SUPABASE_SERVICE_ROLE_KEY");
  await mkdir(join(partial, "database"), { recursive: true });
  await mkdir(join(partial, "storage"), { recursive: true });
  const database = await dumpDatabase();
  const buckets = await backupStorage();
  const manifest = {
    schemaVersion: 1,
    createdAt: new Date().toISOString(),
    mode: dryRun ? "dry-run" : "complete",
    projectHost: supabaseUrl ? new URL(supabaseUrl).host : "dry-run.local",
    database,
    buckets,
    totals: {
      files:
        database.length +
        buckets.reduce((sum, bucket) => sum + bucket.files.length, 0),
      bytes: [...database, ...buckets.flatMap((bucket) => bucket.files)].reduce(
        (sum, file) => sum + file.bytes,
        0,
      ),
    },
  };
  await writeFile(
    join(partial, "manifest.json"),
    `${JSON.stringify(manifest, null, 2)}\n`,
    "utf8",
  );
  await rename(partial, destination);
  console.log(`Backup created: ${destination}`);
  console.log(`Manifest: ${join(destination, "manifest.json")}`);
}
void main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
